// 初始化T表：T[i][b] = L(S(b) << (8*(3-i)))
static void init_T_table() {
    for (int i = 0; i < 4; i++) {  // i=0对应最高位字节，i=3对应最低位
        for (int b = 0; b < 256; b++) {
            uint8_t s = s_box[b];
            uint32_t val = (i == 0) ? (s << 24) :
                           (i == 1) ? (s << 16) :
                           (i == 2) ? (s << 8) : s;
            // 应用线性变换L：val ^ rotl(val,2) ^ rotl(val,10) ^ rotl(val,18) ^ rotl(val,24)
            uint32_t rot2 = (val << 2) | (val >> 30);
            uint32_t rot10 = (val << 10) | (val >> 22);
            uint32_t rot18 = (val << 18) | (val >> 14);
            uint32_t rot24 = (val << 24) | (val >> 8);
            T_table[i][b] = val ^ rot2 ^ rot10 ^ rot18 ^ rot24;
        }
    }
}

static uint32_t rotl(uint32_t data, int bits) {
    return (data << bits) | (data >> (32 - bits));
}

// 基于T表的T变换（直接查表合并计算）
static inline uint32_t t_ttable(uint32_t input) {
    // 拆分4个字节
    uint8_t b0 = (input >> 24) & 0xFF;
    uint8_t b1 = (input >> 16) & 0xFF;
    uint8_t b2 = (input >> 8) & 0xFF;
    uint8_t b3 = input & 0xFF;
    // 查表并异或结果
    return T_table[0][b0] ^ T_table[1][b1] ^ T_table[2][b2] ^ T_table[3][b3];
}

static void sm4_key_expansion(const uint32_t* key, uint32_t* rk) {
    uint32_t k[36];
    for (int i = 0; i < 4; i++) k[i] = key[i] ^ fk[i];
    for (int i = 0; i < 32; i++) {
        uint32_t temp = k[i+1] ^ k[i+2] ^ k[i+3] ^ ck[i];
        // 修改：使用强制类型转换解决缩窄转换问题
        uint8_t b[4] = { 
            static_cast<uint8_t>((temp>>24)&0xFF),
            static_cast<uint8_t>((temp>>16)&0xFF),
            static_cast<uint8_t>((temp>>8)&0xFF),
            static_cast<uint8_t>(temp&0xFF)
        };
        b[0] = s_box[b[0]]; b[1] = s_box[b[1]]; b[2] = s_box[b[2]]; b[3] = s_box[b[3]];
        temp = (b[0]<<24)|(b[1]<<16)|(b[2]<<8)|b[3];
        temp ^= rotl(temp, 13) ^ rotl(temp, 23);
        rk[i] = k[i] ^ temp;
        k[i+4] = rk[i];
    }
}

static void sm4_encrypt_block_ttable(const uint32_t* rk, const uint32_t* input, uint32_t* output) {
    uint32_t state[4] = { input[0], input[1], input[2], input[3] };
    for (int i = 0; i < 32; i++) {
        uint32_t temp = state[1] ^ state[2] ^ state[3] ^ rk[i];
        state[0] ^= t_ttable(temp);  // 使用T表加速
        uint32_t swap = state[0];
        state[0] = state[1];
        state[1] = state[2];
        state[2] = state[3];
        state[3] = swap;
    }
    output[0] = state[3];
    output[1] = state[2];
    output[2] = state[1];
    output[3] = state[0];
}


void sm4_ttable_encrypt(const uint32_t* key, uint32_t* data, int size) {
    clock_t start, end;
    start = clock();

    // 初始化T表
    init_T_table();

    uint32_t rk[32];
    sm4_key_expansion(key, rk);

    for (int i = 0; i < size; i += 4) {
        uint32_t output[4];
        sm4_encrypt_block_ttable(rk, data + i, output);
        memcpy(data + i, output, sizeof(output));
    }

    end = clock();
    double time = (double)(end - start) / CLOCKS_PER_SEC;
    printf("T-Table SM4加密用时：%f seconds\n", time);
}

