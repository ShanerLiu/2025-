    uint32_t key[4] = {0x01234567, 0x89abcdef, 0xfedcba98, 0x76543210};
    uint32_t* data = (uint32_t*)malloc(sizeof(uint32_t) * m_bits);
    if (!data) return 1;
    for (int i = 0; i < m_bits; i++) data[i] = rand();

    sm4_ttable_encrypt(key, data, m_bits);
    free(data);
    return 0;
